def add_genres():
    """为已有电影添加类型数据"""
    conn = get_connection()
    try:
        cursor = conn.cursor(dictionary=True)
        cursor.execute("SELECT id, title FROM movies")
        movies = cursor.fetchall()

        added = 0
        for movie in movies:
            title = movie['title']
            movie_id = movie['id']

            # 匹配类型
            genres = []
            for genre, titles in GENRE_MAP.items():
                for t in titles:
                    if t in title or title in t:
                        genres.append(genre)
                        break

            # 如果没有匹配到，默认添加"剧情"
            if not genres:
                genres = ['剧情']

            # 去重
            genres = list(set(genres))

            # 插入类型关联
            for genre_name in genres:
                genre_id = dao.get_or_create_genre(genre_name)
                if genre_id:
                    dao.link_movie_genre(movie_id, genre_id)
                    added += 1

        print(f"为 {len(movies)} 部电影添加了 {added} 条类型关联")
    finally:
        close_connection(conn)

if __name__ == '__main__':
    add_genres()
